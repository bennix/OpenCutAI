const english = new Map(messages.map(([en, zh]) => [zh, en]));
const chinese = new Map(messages);
export function translate({
	text,
	locale,
}: {
	text: string;
	locale: "zh" | "en";
}): string {
	const direct = (locale === "en" ? english : chinese).get(text);
	if (direct) return direct;
	for (const [en, zh] of messages) {
		const source = locale === "en" ? zh : en;
		const target = locale === "en" ? en : zh;
		if (!source.includes("{")) continue;
		const names = [...source.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
		const escaped = source
			.split(/\{\w+\}/)
			.map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
		const match = text.match(new RegExp(`^${escaped.join("(.+?)")}$`));
		if (match)
			return target.replace(
				/\{(\w+)\}/g,
				(_, name) => match[names.indexOf(name) + 1],
			);
	}
	return text;
}
